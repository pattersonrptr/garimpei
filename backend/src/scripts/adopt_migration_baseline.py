#!/usr/bin/env python3
"""
Adopt databases created by the old start.sh onto the versioned baseline.

The old start.sh deleted alembic/versions and autogenerated a migration with a
random revision ID on every boot. Those databases already have the full
schema, but their alembic_version points to a revision that no longer exists,
so `alembic upgrade head` would fail. This script stamps them with the
baseline revision; new databases and already-versioned ones are left alone.

Safe to run on every start (idempotent).
"""

from sqlalchemy import inspect, text

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from src.app.infrastructure.database_config import engine

BASELINE_REVISION = "02608ed9b827"


def main() -> None:
    config = Config("alembic.ini")
    known = {
        rev.revision for rev in ScriptDirectory.from_config(config).walk_revisions()
    }

    tables = set(inspect(engine).get_table_names())
    if "users" not in tables:
        print("Empty database: migrations will create the schema.")
        return

    current = None
    if "alembic_version" in tables:
        with engine.connect() as conn:
            current = conn.execute(
                text("SELECT version_num FROM alembic_version")
            ).scalar()

    if current in known:
        print(f"Database already on a versioned revision ({current}).")
        return

    print(
        f"Unversioned schema found (revision {current!r}); "
        f"stamping baseline {BASELINE_REVISION}."
    )
    command.stamp(config, BASELINE_REVISION, purge=True)


if __name__ == "__main__":
    main()
